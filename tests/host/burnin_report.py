#!/usr/bin/env python3
"""Full-day always-on burn-in report from the host model (stand-in fonts -> ESTIMATES).

Simulates the 1440 one-minute low-power updates of a day for every size and both font-size mappings with the
brightest colours (white/white) and writes docs/burn-in-report.md.
Usage: python3 tests/host/burnin_report.py [minutes]   (default 1440)
"""
import os
import sys

import face_model as m

minutes = int(sys.argv[1]) if len(sys.argv) > 1 else 1440
rows = []
for mapping in ("line", "digit"):
    for size in (0, 1, 2):
        tf, _ = m.choose_time_font(size, mapping)
        lit, lum, run = m.burn_in_run(size, 0xFFFFFF, 0xFFFFFF, 0, minutes, mapping=mapping, steps=88888)
        rows.append((mapping, m.SIZE_NAMES[size], tf.name, lit, lum, run))
        print(rows[-1], flush=True)

out = os.path.join(m.ROOT, "docs", "burn-in-report.md")
with open(out, "w", encoding="utf-8") as fh:
    fh.write("# Always-on burn-in report (host model - ESTIMATE)\n\n")
    fh.write("Generated by `python3 tests/host/burnin_report.py %d`: %d consecutive one-minute low-power updates "
             "from 00:00, hour and minute colour white (worst case), steps 88,888, 24 h clock. Stand-in fonts "
             "(Rajdhani Medium / Roboto, see tests/host/face_model.py), so these are estimates; the real check is "
             "the simulator Heat Map (File > View Screen Heat Map) - see README.\n\n" % (minutes, minutes))
    fh.write("Limits (AMOLED FAQ / UX guidelines): < 10 % of pixels on, < 10 % luminance (Venu 2 and later), "
             "no pixel on for more than 3 minutes.\n\n")
    fh.write("| font-size mapping | size | font chosen | max pixels on | max luminance | longest run (min) |\n")
    fh.write("|---|---|---|---|---|---|\n")
    for mapping, size, name, lit, lum, run in rows:
        fh.write("| %s | %s | %s | %.2f %% | %.2f %% | %d |\n" % (mapping, size, name, 100 * lit, 100 * lum, run))
print("written", out)
