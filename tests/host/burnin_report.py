#!/usr/bin/env python3
"""Full-day always-on burn-in report from the host model.

Simulates the 1440 one-minute low-power updates of a day for every size with the brightest colours
(white/white) and writes docs/burn-in-report.md.
  CIQ_DEVICE_FONTS=~/.Garmin/ConnectIQ/Fonts python3 tests/host/burnin_report.py   # font-accurate (device TTFs)
  python3 tests/host/burnin_report.py [minutes]                                    # stand-in fonts (estimate)
With device fonts only the "line" font-size mapping is run: real simulator screenshots showed it is the one the
device uses (identical glyph heights, see DECISIONS D-23).
"""
import os
import sys

import face_model as m

minutes = int(sys.argv[1]) if len(sys.argv) > 1 else 1440
mappings = ("line",) if m.DEVICE_FONTS else ("line", "digit")
rows = []
for mapping in mappings:
    for size in (0, 1, 2):
        tf, _ = m.choose_time_font(size, mapping)
        lit, lum, run = m.burn_in_run(size, 0xFFFFFF, 0xFFFFFF, 0, minutes, mapping=mapping, steps=88888)
        rows.append((mapping, m.SIZE_NAMES[size], tf.name, lit, lum, run))
        print(rows[-1], flush=True)

REAL = """## Real simulator measurements (SDK 9.3.0, fenix9pro47mm device files and fonts)

Frames captured from the Connect IQ simulator in Settings > Display Mode > Always-On (docs/screenshots/aod_*.png),
pixels counted inside the round 454 px screen; share of all 454x454 pixels.

| frame | pixels on | mean luminance |
|---|---|---|
| Small, white/cyan, 19:23 | 2.12 % | 1.38 % |
| Medium, white/orange, 19:27 | 2.34 % | 1.52 % |
| Large, yellow/white, 19:25 | 2.67 % | 2.07 % |
| Large, white/white, 19:31 | 2.49 % | 2.01 % |

Simulator File > View Screen Heat Map > 24-Hour Simulation (docs/screenshots/burnin24h_*.png):

| build | result | peak luminance usage |
|---|---|---|
| Small, white/cyan | no screen burn-in detected | 1.19 % |
| Medium, white/orange | no screen burn-in detected | 1.51 % |
| Large, yellow/white | no screen burn-in detected | 1.82 % |
| Large, white/white | no screen burn-in detected | 1.98 % |

"""

out = os.path.join(m.ROOT, "docs", "burn-in-report.md")
with open(out, "w", encoding="utf-8") as fh:
    kind = "font-accurate" if m.DEVICE_FONTS else "ESTIMATE, stand-in fonts"
    fh.write("# Always-on burn-in report\n\n")
    fh.write(REAL)
    fh.write("## Full day, host model (%s)\n\n" % kind)
    fh.write("Generated by `python3 tests/host/burnin_report.py %d` with %s: %d consecutive one-minute low-power "
             "updates from 00:00, hour and minute colour white (worst case), steps 88,888, 24 h clock. With the "
             "device fonts the model is within 0.1 percentage point of the real frames above.\n\n"
             % (minutes, m.FONT_SOURCE, minutes))
    fh.write("Limits (AMOLED FAQ / UX guidelines): < 10 % of pixels on, < 10 % luminance (Venu 2 and later), "
             "no pixel on for more than 3 minutes.\n\n")
    fh.write("| font-size mapping | size | font chosen | max pixels on | max luminance | longest run (min) |\n")
    fh.write("|---|---|---|---|---|---|\n")
    for mapping, size, name, lit, lum, run in rows:
        fh.write("| %s | %s | %s | %.2f %% | %.2f %% | %d |\n" % (mapping, size, name, 100 * lit, 100 * lum, run))
print("written", out)
